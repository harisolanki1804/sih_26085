/**
 * Ray-casting point-in-polygon test.
 */
function pointInPolygon(lat, lon, polygon) {
  let inside = false
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const yi = polygon[i][0], xi = polygon[i][1]
    const yj = polygon[j][0], xj = polygon[j][1]
    const intersect = ((yi > lat) !== (yj > lat)) &&
      (lon < (xj - xi) * (lat - yi) / (yj - yi) + xi)
    if (intersect) inside = !inside
  }
  return inside
}

/**
 * Check if a point is within India's land area.
 */
export function isInsideIndia(lat, lon) {
  if (lat < 6.0 || lat > 37.0 || lon < 67.0 || lon > 98.0) return false
  if (!pointInPolygon(lat, lon, INDIA_MAIN)) return false
  if (pointInPolygon(lat, lon, SRI_LANKA)) return false
  return true
}

/**
 * Mumbai land boundary — masks Arabian Sea and Thane Creek.
 */
export function isInsideMumbaiLand(lat, lon) {
  if (lat < 18.88 || lat > 19.26 || lon < 72.78 || lon > 73.00) return false

  // Mumbai coastline (simplified)
  const coastLon = 72.80 + (lat - 18.88) * 0.05
  if (lon < coastLon) return false

  // Thane Creek
  if (lat > 19.05 && lon > 72.96) return false

  // Mahim Bay
  if (lat < 19.02 && lon < 72.83 && lon > 72.78) return false

  return true
}
